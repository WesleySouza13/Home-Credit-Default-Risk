WITH tb_train as (
SELECT SK_ID_CURR,
TARGET,
NAME_CONTRACT_TYPE, CODE_GENDER, FLAG_OWN_CAR, FLAG_OWN_REALTY,
CNT_CHILDREN, AMT_INCOME_TOTAL, AMT_CREDIT, AMT_ANNUITY,
AMT_GOODS_PRICE, NAME_TYPE_SUITE, NAME_INCOME_TYPE,
NAME_EDUCATION_TYPE, NAME_FAMILY_STATUS, NAME_HOUSING_TYPE,
REGION_POPULATION_RELATIVE,
CASE WHEN DAYS_EMPLOYED = 365243 THEN NULL
    ELSE (DAYS_EMPLOYED*-1)/365 END AS YEARS_EMPLOYED, 
(DAYS_REGISTRATION*-1) AS DAYS_REGISTRATION ,
(DAYS_ID_PUBLISH*-1) AS DAYS_ID_PUBLISH , FLAG_EMP_PHONE, FLAG_WORK_PHONE,
FLAG_CONT_MOBILE, FLAG_PHONE, FLAG_EMAIL, CNT_FAM_MEMBERS,
REGION_RATING_CLIENT, REGION_RATING_CLIENT_W_CITY,
WEEKDAY_APPR_PROCESS_START, HOUR_APPR_PROCESS_START,
REG_REGION_NOT_LIVE_REGION, REG_REGION_NOT_WORK_REGION,
LIVE_REGION_NOT_WORK_REGION, REG_CITY_NOT_LIVE_CITY,
REG_CITY_NOT_WORK_CITY, LIVE_CITY_NOT_WORK_CITY,
ORGANIZATION_TYPE, EXT_SOURCE_2, OBS_30_CNT_SOCIAL_CIRCLE,
DEF_30_CNT_SOCIAL_CIRCLE, OBS_60_CNT_SOCIAL_CIRCLE,
DEF_60_CNT_SOCIAL_CIRCLE, FLAG_DOCUMENT_3,
FLAG_DOCUMENT_4, FLAG_DOCUMENT_5, FLAG_DOCUMENT_6,
FLAG_DOCUMENT_7, FLAG_DOCUMENT_8, FLAG_DOCUMENT_9,
FLAG_DOCUMENT_10, FLAG_DOCUMENT_11, FLAG_DOCUMENT_12,
FLAG_DOCUMENT_13, FLAG_DOCUMENT_14, FLAG_DOCUMENT_15,
FLAG_DOCUMENT_16, FLAG_DOCUMENT_17, FLAG_DOCUMENT_18,
FLAG_DOCUMENT_19, FLAG_DOCUMENT_20, FLAG_DOCUMENT_21,
AMT_REQ_CREDIT_BUREAU_HOUR, AMT_REQ_CREDIT_BUREAU_DAY,
AMT_REQ_CREDIT_BUREAU_WEEK, AMT_REQ_CREDIT_BUREAU_MON,
AMT_REQ_CREDIT_BUREAU_QRT, AMT_REQ_CREDIT_BUREAU_YEAR,
(DAYS_BIRTH*-1)/365 as AGE,
AMT_INCOME_TOTAL / NULLIF(AMT_CREDIT, 0) AS INCOME_PER_CREDIT,
AMT_GOODS_PRICE / NULLIF(AMT_CREDIT, 0) AS PRICE_PER_CREDIT,
AMT_ANNUITY / NULLIF(AMT_INCOME_TOTAL, 0) AS ANNUITY_PER_INCOME,
AMT_INCOME_TOTAL / NULLIF(CNT_FAM_MEMBERS, 0) AS INCOME_PER_FAMILY_MEMBER,
ROUND(DAYS_LAST_PHONE_CHANGE*-1/365,2) AS YEARS_LAST_PHONE_CHANGE, 
(AMT_GOODS_PRICE - AMT_CREDIT) AS DIFF_PRICE,
-- features de contato e familia 
(FLAG_CONT_MOBILE + FLAG_MOBIL + FLAG_EMP_PHONE + FLAG_WORK_PHONE + FLAG_CONT_MOBILE + FLAG_PHONE + FLAG_EMAIL) AS FLAG_CONTACT_SUM,
(CNT_FAM_MEMBERS - CNT_CHILDREN) AS CNT_FAM_NO_CHILDREN,

(FLAG_DOCUMENT_4+FLAG_DOCUMENT_5+ FLAG_DOCUMENT_6+ FLAG_DOCUMENT_7+FLAG_DOCUMENT_8+ FLAG_DOCUMENT_9+ FLAG_DOCUMENT_10+ FLAG_DOCUMENT_11+ FLAG_DOCUMENT_12+
FLAG_DOCUMENT_13+ FLAG_DOCUMENT_14+ FLAG_DOCUMENT_15+ FLAG_DOCUMENT_16+ FLAG_DOCUMENT_17+ FLAG_DOCUMENT_18+
FLAG_DOCUMENT_19+FLAG_DOCUMENT_20+ FLAG_DOCUMENT_21) AS SUM_FLAG_DOC

FROM application_train  
),

tb_bureau as(
SELECT 
    SK_ID_CURR,
    SK_ID_BUREAU,
    AMT_CREDIT_SUM,
    AMT_CREDIT_SUM_DEBT,
    AMT_CREDIT_SUM_OVERDUE,
    CREDIT_DAY_OVERDUE,
    CREDIT_ACTIVE
FROM bureau
),

tb_bureau_balance AS (
SELECT SK_ID_BUREAU, 
    COUNT(SK_ID_BUREAU) AS FREQ, 
    AVG(MONTHS_BALANCE) AS AVG_MONTHS_BALANCE, 
    MAX(CASE WHEN STATUS = '0' THEN 1 ELSE 0 END) AS HAS_STATUS_0
    FROM bureau_balance
    GROUP BY SK_ID_BUREAU
), 
tb_bureau_final AS (
    SELECT T1.*, 
    COALESCE(T2.FREQ, 0) AS FREQ,
    COALESCE(T2.HAS_STATUS_0, 0) AS HAS_STATUS_0,
    COALESCE(T2.AVG_MONTHS_BALANCE, 0) AS AVG_MONTHS_BALANCE,
    CASE WHEN T2.FREQ IS NULL THEN 0
    ELSE 1 END AS HAS_BUREAU_BALANCE
    FROM tb_bureau AS T1
    LEFT JOIN tb_bureau_balance AS T2
    ON T1.SK_ID_BUREAU = T2.SK_ID_BUREAU
),
tb_bureau_agg AS (
SELECT
    SK_ID_CURR, 
    COUNT(SK_ID_CURR) AS BUREAU_COUNT, 
    SUM(AMT_CREDIT_SUM) AS TOTAL_CREDIT_SUM, 
    SUM(AMT_CREDIT_SUM_DEBT) AS TOTAL_CREDIT_DEBT, 
    MAX(CREDIT_DAY_OVERDUE) AS  MAX_CREDIT_OVER,
    AVG(FREQ) AS AVG_FREQ_BUREAU, 
    AVG(HAS_STATUS_0) AS  PCT_CONTRACTS_STATUS_0, 
    AVG(AVG_MONTHS_BALANCE) AS AVG_MONTHS_BALANCE,
    SUM(HAS_BUREAU_BALANCE) AS CONTRACTS_WITH_BALANCE
    FROM tb_bureau_final
    GROUP BY  SK_ID_CURR
)

SELECT 
    T1.*,
    COALESCE(T2.BUREAU_COUNT, 0) AS BUREAU_COUNT,
    COALESCE(T2.TOTAL_CREDIT_SUM, 0) AS TOTAL_CREDIT_SUM,
    COALESCE(T2.TOTAL_CREDIT_DEBT, 0) AS TOTAL_CREDIT_DEBT,
    COALESCE(T2.PCT_CONTRACTS_STATUS_0, 0) AS PCT_CONTRACTS_STATUS_0,
    COALESCE(T2.AVG_MONTHS_BALANCE, 0) AS AVG_MONTHS_BALANCE,
    COALESCE(T2.CONTRACTS_WITH_BALANCE, 0) AS CONTRACTS_WITH_BALANCE
FROM tb_train AS T1
LEFT JOIN tb_bureau_agg AS T2
ON T1.SK_ID_CURR = T2.SK_ID_CURR
